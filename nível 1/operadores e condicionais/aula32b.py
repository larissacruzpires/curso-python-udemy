# Comando elif (controle de decisão multidirecional): Valores das frutas

fruta = input("Digite a fruta: ")
if (fruta == 'Banana'):
    print("O kg da Banana é 5,23")
elif (fruta == 'Maça'):
    print("O kg da Maça é 12,10")
elif (fruta == 'Cereja'):
    print("O kg da Cereja é 58,00")
else:
    print("Desculpe. Não temos ", fruta)
